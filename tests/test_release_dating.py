"""Dated artifacts are immutable; a retry is the same release, not today's new PDF."""
import json
import subprocess
import pytest
from pathfinder import paper, presentation, release
from stubcampaign import make
from pathfinder.stub import READABLE, BIB


def cleared(tmp_path):
    c = make(tmp_path, release={"disclosure": "disclosure.tex"})
    (c.root / "disclosure.tex").write_text("The outputs were generated by Pathfinder (\\url{https://github.com/vd1/pathfinder}) with no human input after the choice of sources.")
    pd = c.thread_dir("Q1P1") / "paper"
    d = pd / "presentation" / "pass"; d.mkdir(parents=True)
    tex = READABLE.replace('\\date{}', '\\date{\\today}')
    (d / "paper.tex").write_text(tex)
    (d / "references.bib").write_text(BIB)
    presentation._save(c, "Q1P1", state="CLEARED", stage="pass", sha256=presentation.sha(tex))
    paper._set(c, "Q1P1", status="CLEARED", cleared_sha256=presentation.sha(tex))
    return c, pd


def test_timestamp_is_shared_by_source_pdf_visible_date_and_hashes(tmp_path, monkeypatch):
    c, pd = cleared(tmp_path)
    out = release.run(c, "Q1P1", timestamp="20261019T142530Z")
    d = pd / "release" / "20261019T142530Z"
    meta = json.loads((d / "manifest.json").read_text())
    assert out['path'].endswith('paper-20261019T142530Z.pdf')
    tex = (d / meta['tex']).read_text()
    assert '\\date{Released 2026-10-19 14:25:30 UTC}' in tex and '\\today' not in tex
    text = subprocess.run(['pdftotext', str(d / meta['pdf']), '-'], capture_output=True, text=True, check=True).stdout
    assert 'Released 2026-10-19 14:25:30 UTC' in ' '.join(text.split())
    assert meta['sha256'] == {name: release._digest(d / name) for name in meta['sha256']}
    assert (pd / 'release' / 'paper.pdf').read_bytes() == (d / meta['pdf']).read_bytes()
    before = (d / meta['pdf']).read_bytes()
    monkeypatch.setattr(paper, 'build', lambda *a, **kw: pytest.fail('published retry must not recompile'))
    assert release.run(c, 'Q1P1')['timestamp'] == '20261019T142530Z'
    assert (d / meta['pdf']).read_bytes() == before
    (d / meta['tex']).write_text(tex + '\nchanged')
    with pytest.raises(SystemExit, match='changed or missing'):
        release.run(c, 'Q1P1')


def test_failed_build_retries_same_timestamp_and_new_release_preserves_old(tmp_path, monkeypatch):
    c, pd = cleared(tmp_path)
    real = paper.build
    monkeypatch.setattr(paper, 'build', lambda *a, **kw: (False, 'test failure'))
    with pytest.raises(SystemExit, match='does not build'):
        release.run(c, 'Q1P1', timestamp='20261019T142530Z')
    assert not (pd / 'release' / 'release.json').exists()
    monkeypatch.setattr(paper, 'build', real)
    assert release.run(c, 'Q1P1')['timestamp'] == '20261019T142530Z'
    first = pd / 'release' / '20261019T142530Z' / 'paper-20261019T142530Z.pdf'
    digest = release._digest(first)
    assert release.run(c, 'Q1P1', timestamp='20261019T142531Z')['timestamp'] == '20261019T142531Z'
    assert release._digest(first) == digest


def test_collision_and_failed_pdf_text_validation_do_not_publish(tmp_path, monkeypatch):
    c, pd = cleared(tmp_path)
    real = release.leak_check
    monkeypatch.setattr(release, 'leak_check', lambda *a: ['test pipeline leak'])
    with pytest.raises(SystemExit, match='leak check failed'):
        release.run(c, 'Q1P1', timestamp='20261019T142530Z')
    assert not (pd / 'release' / 'release.json').exists()
    assert paper.status(c, 'Q1P1')['status'] == 'CLEARED'
    (c.root / 'disclosure.tex').write_text('Changed acknowledgement.')
    monkeypatch.setattr(release, 'leak_check', real)
    with pytest.raises(SystemExit, match='timestamp already used'):
        release.run(c, 'Q1P1', timestamp='20261019T142530Z')


def test_failed_pdf_text_extraction_is_not_a_validated_release(tmp_path, monkeypatch):
    c, pd = cleared(tmp_path)
    real = subprocess.run
    def run(args, **kwargs):
        if args[0] == 'pdftotext':
            return subprocess.CompletedProcess(args, 1, stdout='', stderr='test extraction failure')
        return real(args, **kwargs)
    monkeypatch.setattr(subprocess, 'run', run)
    with pytest.raises(SystemExit, match='text extraction failed'):
        release.run(c, 'Q1P1', timestamp='20261019T142530Z')
    assert not (pd / 'release' / 'release.json').exists()
